const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const src = name => fs.readFileSync(path.join(__dirname,'..','app','src','main','java','com','example','maxsignalcopy',name),'utf8');
const main = src('MainActivity.kt');
const trade = src('TradeSession.kt');
const svc = src('TradeForegroundService.kt');
const manifest = fs.readFileSync(path.join(__dirname,'..','app','src','main','AndroidManifest.xml'),'utf8');
assert.match(manifest,/FOREGROUND_SERVICE/);
assert.match(manifest,/WAKE_LOCK/);
assert.match(manifest,/foregroundServiceType="shortService"/);
assert.match(svc,/START_NOT_STICKY/);
assert.match(svc,/165_000L/);
assert.match(svc,/onTimeout\(startId: Int, fgsType: Int\)/);
assert.match(svc,/TradeSession\.stop\(\)/);
assert.match(trade,/TradeForegroundService\.start\(context\)/);
assert.match(trade,/TradeForegroundService\.finish\(context\)/);
assert.match(trade,/SignalMailbox\.finish\(context, result, detail, safeToRetry\)/);
assert.match(main,/if \(!TradeSession\.isActive\(\)\) SignalMailbox\.markInterrupted/);
assert.match(main,/if \(!TradeSession\.isActive\(\)\) \{/);
assert.doesNotMatch(main,/if \(::automation\.isInitialized && automation\.isActive\(\)\) automation\.stop\(\)/);
assert.match(main,/TradeSession\.browser\(this\)/);
assert.match(main,/TradeSession\.start\(this, code\)/);
assert.ok(!svc.includes('BrowserAutomation('), 'service must never create a new trading engine');
assert.ok(!svc.includes('claimManual'), 'service must never claim a new code');
console.log('Active-order background service safety smoke tests passed.');
